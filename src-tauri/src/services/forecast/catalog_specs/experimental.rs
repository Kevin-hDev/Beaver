struct ExperimentalModelInput {
    id: &'static str,
    family_id: &'static str,
    display_name: &'static str,
    provider_id: &'static str,
    frequencies: &'static str,
    params: &'static str,
    size_mb: u32,
    ram_mb: u32,
    vram_mb: Option<u32>,
    hf_repo: Option<&'static str>,
    hf_revision: Option<&'static str>,
    github_repo: &'static str,
    github_revision: &'static str,
}

const fn build(input: ExperimentalModelInput) -> ForecastModelSpec {
    ForecastModelSpec {
        id: input.id,
        provider_id: input.provider_id,
        family_id: input.family_id,
        display_name: input.display_name,
        params: input.params,
        size_mb: input.size_mb,
        ram_mb: input.ram_mb,
        vram_mb: input.vram_mb,
        cpu_supported: true,
        gpu_supported: true,
        multivariate: false,
        covariates: false,
        horizon_max: 1024,
        frequencies: input.frequencies,
        hf_repo: input.hf_repo,
        hf_revision: input.hf_revision,
        github_repo: Some(input.github_repo),
        github_revision: Some(input.github_revision),
        is_cloud: false,
    }
}
