use super::{
    favicon_events::{BrowserFaviconIcon, BrowserFaviconSnapshot, EVENT_VERSION, FAVICON_EVENT},
    favicon_policy::{MAX_FAVICONS, MAX_PNG_BYTES},
};
use ts_rs::TS;

fn bindings() -> String {
    let config = ts_rs::Config::default();
    format!("// @generated by Rust favicon_contract_tests::export_favicon_contract. Do not edit.\n\nexport {}\nexport {}\nexport const FAVICON_EVENT = {:?};\nexport const FAVICON_EVENT_VERSION = {};\nexport const MAX_FAVICONS = {};\nexport const MAX_FAVICON_PNG_BYTES = {};\n",
        BrowserFaviconIcon::decl(&config), BrowserFaviconSnapshot::decl(&config),
        FAVICON_EVENT, EVENT_VERSION, MAX_FAVICONS, MAX_PNG_BYTES)
}

#[test]
fn checked_in_favicon_contract_matches_rust() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../src/components/internal-browser/browser-favicon-contract.ts");
    assert_eq!(
        std::fs::read_to_string(path).unwrap().replace("\r\n", "\n"),
        bindings()
    );
}

#[test]
#[ignore = "explicit contract generation"]
fn export_favicon_contract() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../src/components/internal-browser/browser-favicon-contract.ts");
    std::fs::write(path, bindings()).unwrap();
}

