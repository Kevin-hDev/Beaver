#[test]
fn snapshots_isolate_conversations_and_remove_closed_icons() {
    use super::{
        browser_view_key::BrowserViewKey, favicon_events::snapshot, favicon_state::FaviconState,
    };
    let mut state = FaviconState::default();
    let a = BrowserViewKey {
        session_id: "a".into(),
        tab_id: "one".into(),
    };
    let b = BrowserViewKey {
        session_id: "b".into(),
        tab_id: "two".into(),
    };
    state.begin_document(a.clone(), 1);
    state.begin_document(b, 2);
    state.entries[0].png = Some("image-a".into());
    state.entries[1].png = Some("image-b".into());
    let before = snapshot(&state, "a");
    assert_eq!(before.icons.len(), 1);
    assert_eq!(before.icons[0].png_base64, "image-a");
    state.release_view(&a, 1);
    let after = snapshot(&state, "a");
    assert!(after.icons.is_empty());
    assert!(after.revision > before.revision);
}
